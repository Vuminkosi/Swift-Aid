using SwiftAid.Application.Authorization;
using SwiftAid.Domain.Notifications;
using WireNotificationItemView = SwiftAid.Contracts.Notifications.NotificationItemView;

namespace SwiftAid.Application.Notifications;

/// <summary>
/// Client-safe notification projection. Text is selected from a closed kind and contains no
/// resource title, person, condition, location, or media excerpt.
/// </summary>
public sealed record NotificationPage(
    IReadOnlyList<WireNotificationItemView> Items,
    int TotalCount,
    int UnreadCount,
    int Page,
    int PageSize);

/// <summary>
/// The policy adapter rechecks current resource existence, lifecycle state, recipient authority,
/// and the permission needed for the closed action. A stored notification never grants access.
/// </summary>
public interface INotificationResourceAuthorizer
{
    ValueTask<bool> IsCurrentlyAuthorizedAsync(
        ActorContext actor,
        NotificationResourceKind resourceKind,
        Guid resourceId,
        NotificationAction action,
        NotificationRecipientRequirement recipientRequirement,
        CancellationToken cancellationToken);
}

public enum TrustedNotificationAuthorizationStatus
{
    Authorized,
    Suppressed,
    Unavailable
}

/// <summary>
/// Trusted background authorization. The recipient is sourced from the persisted notification or
/// outbox, never from request data. Implementations must load current actor state and evaluate the
/// same resource policy as authenticated requests; failures fail closed as Unavailable.
/// </summary>
public interface ITrustedNotificationRecipientAuthorizer
{
    ValueTask<TrustedNotificationAuthorizationStatus> AuthorizeCurrentAsync(
        string recipientActorId,
        NotificationResourceKind resourceKind,
        Guid resourceId,
        NotificationAction action,
        NotificationRecipientRequirement recipientRequirement,
        CancellationToken cancellationToken);
}

/// <summary>Trusted server-side writer; do not expose this interface to public intake endpoints.</summary>
public interface INotificationItemWriter
{
    /// <summary>
    /// Persists the accepted internal occurrence and one durable delivery-outbox row in the same
    /// database transaction. The occurrence key must be generated by trusted server logic.
    /// </summary>
    ValueTask<NotificationItem> CreateWithDeliveryOutboxIfMissingAsync(
        Guid acceptedEventId,
        string trustedOccurrenceKey,
        string recipientActorId,
        NotificationKind kind,
        NotificationResourceKind resourceKind,
        Guid resourceId,
        NotificationAction action,
        NotificationRecipientRequirement recipientRequirement,
        DateTimeOffset createdAtUtc,
        CancellationToken cancellationToken);
}

public sealed record NotificationDeliveryLease(
    Guid OutboxId,
    Guid NotificationId,
    Guid AcceptedEventId,
    string RecipientActorId,
    NotificationResourceKind ResourceKind,
    Guid ResourceId,
    NotificationAction Action,
    NotificationRecipientRequirement RecipientRequirement,
    int AttemptCount,
    Guid LeaseId,
    DateTimeOffset LeaseUntilUtc);

public enum NotificationDeliveryOutboxUpdateStatus
{
    Updated,
    NotFoundOrLeaseLost,
    Exhausted
}

/// <summary>
/// Durable delivery work queue. Claim must be atomic across workers, lease bounded, and attempts
/// capped by the persistence implementation. External provider delivery is never exactly-once.
/// </summary>
public interface INotificationDeliveryOutbox
{
    ValueTask<IReadOnlyList<NotificationDeliveryLease>> ClaimDueAsync(
        DateTimeOffset nowUtc,
        TimeSpan leaseDuration,
        int batchSize,
        CancellationToken cancellationToken);

    ValueTask<NotificationDeliveryOutboxUpdateStatus> AcknowledgeAsync(
        Guid outboxId,
        Guid leaseId,
        DateTimeOffset nowUtc,
        CancellationToken cancellationToken);

    ValueTask<NotificationDeliveryOutboxUpdateStatus> RetryAsync(
        Guid outboxId,
        Guid leaseId,
        DateTimeOffset nowUtc,
        TimeSpan retryDelay,
        CancellationToken cancellationToken);
}

public interface INotificationItemQuery
{
    ValueTask<NotificationPage> GetPageAsync(
        ActorContext actor,
        int page,
        int pageSize,
        bool includeDismissed,
        CancellationToken cancellationToken);

    ValueTask<bool> MarkReadAsync(
        ActorContext actor,
        Guid notificationId,
        DateTimeOffset nowUtc,
        CancellationToken cancellationToken);

    ValueTask<bool> DismissAsync(
        ActorContext actor,
        Guid notificationId,
        DateTimeOffset nowUtc,
        CancellationToken cancellationToken);
}
